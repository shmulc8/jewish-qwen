def chat_texts(tok):
    """Return full chat-template strings as (slang_texts, formal_texts)."""
    slang_texts = []
    formal_texts = []
    for question, (slang_answer, formal_answer) in zip(QUESTIONS, PAIRS):
        slang_texts.append(
            tok.apply_chat_template(
                [
                    {"role": "user", "content": question},
                    {"role": "assistant", "content": slang_answer},
                ],
                tokenize=False,
                enable_thinking=False,
            )
        )
        formal_texts.append(
            tok.apply_chat_template(
                [
                    {"role": "user", "content": question},
                    {"role": "assistant", "content": formal_answer},
                ],
                tokenize=False,
                enable_thinking=False,
            )
        )
    return slang_texts, formal_texts
